# ---- Captures (screenshot, camera, mic) ----------------------------------


class CaptureOut(BaseModel):
    """A captured media blob (screenshot / camera snapshot / mic clip)."""

    model_config = ConfigDict(extra="forbid")

    id: str
    kind: str  # 'screenshot' | 'camera' | 'microphone'
    captured_at: str
    mime_type: str
    bytes_size: int
    # Base64 inline body — avoids MinIO dependency for this slice. The
    # dashboard decodes and renders inline; for very large captures we
    # can swap this for a signed URL later without changing the contract.
    body_b64: str


